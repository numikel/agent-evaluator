/**
 * Demo chatbot fixture: a tiny Hono app that serves the vanilla-JS chat page, streams scripted
 * replies over SSE, generates invoice PDFs and accepts uploads. Used by the E2E tests, the README
 * quick start and manual testing (`npm run demo`).
 */

import { readFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { serve } from "@hono/node-server";
import { Hono } from "hono";
import { streamSSE } from "hono/streaming";
import {
	capitalize,
	type DemoMessage,
	type DemoMode,
	INVOICE_YEAR,
	invoiceAttachment,
	isDemoMode,
	isMonth,
	reply,
} from "./brain.js";
import { buildPdf } from "./pdf.js";

export const DEFAULT_DEMO_PORT = 3999;

export interface DemoAppOptions {
	/** Multiplier for every artificial delay (token pacing, `slow` mode). `0` makes tests instant. */
	delayScale?: number;
}

export interface DemoServer {
	url: string;
	port: number;
	app: Hono;
	close(): Promise<void>;
}

interface ChatRequest {
	messages: DemoMessage[];
	mode?: DemoMode;
}

const TOKEN_DELAY_MS = 25;
const HEARTBEAT_MS = 500;
const PUBLIC_DIR = join(dirname(fileURLToPath(import.meta.url)), "public");

const STATIC_FILES: Record<string, { file: string; type: string }> = {
	"/": { file: "index.html", type: "text/html; charset=utf-8" },
	"/index.html": { file: "index.html", type: "text/html; charset=utf-8" },
	"/app.js": { file: "app.js", type: "text/javascript; charset=utf-8" },
	"/style.css": { file: "style.css", type: "text/css; charset=utf-8" },
};

function parseChatRequest(body: unknown): ChatRequest | undefined {
	if (typeof body !== "object" || body === null) return undefined;
	const { messages, mode } = body as { messages?: unknown; mode?: unknown };
	if (!Array.isArray(messages)) return undefined;
	const parsed: DemoMessage[] = [];
	for (const item of messages) {
		if (typeof item !== "object" || item === null) return undefined;
		const { role, text } = item as { role?: unknown; text?: unknown };
		if ((role !== "user" && role !== "bot") || typeof text !== "string") return undefined;
		parsed.push({ role, text });
	}
	const request: ChatRequest = { messages: parsed };
	if (isDemoMode(mode)) request.mode = mode;
	return request;
}

/** Duck-typed `File` check: the global `File` class differs between runtimes (e.g. jsdom). */
function isUploadedFile(value: unknown): value is File {
	return (
		typeof value === "object" &&
		value !== null &&
		typeof (value as File).name === "string" &&
		typeof (value as File).size === "number"
	);
}

/** Split text into whitespace-preserving tokens so the client can concatenate them verbatim. */
function tokenize(text: string): string[] {
	return text.match(/\S+\s*|\s+/g) ?? [];
}

export function createDemoApp(options: DemoAppOptions = {}): Hono {
	const delayScale = options.delayScale ?? 1;
	const state = { uploads: [] as string[], chats: 0 };
	const app = new Hono();

	app.get("/api/invoice/:file", (c) => {
		const month = c.req
			.param("file")
			.replace(/\.pdf$/i, "")
			.toLowerCase();
		if (!isMonth(month) || !/\.pdf$/i.test(c.req.param("file"))) {
			return c.json({ error: "unknown invoice" }, 404);
		}
		const label = `${capitalize(month)} ${INVOICE_YEAR}`;
		const pdf = buildPdf([
			`Invoice ${label}`,
			"Acme Cloud Services Ltd.",
			"Customer: 4471",
			`Billing period: ${label}`,
			"",
			"Description                      Qty      Amount",
			"Starter plan (monthly)             1      99.00 EUR",
			"Additional storage (50 GB)         1      21.00 EUR",
			"",
			"Total due: 120.00 EUR",
			"Payment terms: 14 days. Thank you for your business.",
			"This document was generated by the agent-evaluator demo chatbot.",
		]);
		return c.body(pdf, 200, {
			"content-type": "application/pdf",
			"content-length": String(pdf.byteLength),
			"content-disposition": `attachment; filename="${invoiceAttachment(month).name}"`,
			"cache-control": "no-store",
		});
	});

	app.post("/api/chat", async (c) => {
		let raw: unknown;
		try {
			raw = await c.req.json();
		} catch {
			return c.json({ error: "body must be JSON" }, 400);
		}
		const request = parseChatRequest(raw);
		if (!request) {
			return c.json({ error: "expected { messages: {role, text}[] , mode? }" }, 400);
		}
		const queryMode = c.req.query("mode");
		const mode: DemoMode = isDemoMode(queryMode) ? queryMode : (request.mode ?? "normal");
		const answer = reply(request.messages, mode);
		state.chats += 1;

		return streamSSE(c, async (stream) => {
			const tokens = tokenize(answer.text);
			await stream.sleep(answer.delayMs * delayScale);
			const stopAt = answer.streamForever
				? Math.max(1, Math.floor(tokens.length / 3))
				: tokens.length;
			for (const token of tokens.slice(0, stopAt)) {
				if (stream.aborted) return;
				await stream.writeSSE({ event: "token", data: JSON.stringify({ text: token }) });
				await stream.sleep(TOKEN_DELAY_MS * delayScale);
			}
			if (answer.streamForever) {
				await stream.writeSSE({
					event: "error",
					data: JSON.stringify({
						message: "Upstream model timed out; the reply will not complete.",
					}),
				});
				while (!stream.aborted && !stream.closed) {
					await stream.sleep(HEARTBEAT_MS);
					await stream.write(": keep-alive\n\n");
				}
				return;
			}
			await stream.writeSSE({
				event: "done",
				data: JSON.stringify({ text: answer.text, attachment: answer.attachment ?? null }),
			});
		});
	});

	app.post("/api/upload", async (c) => {
		let body: Record<string, unknown>;
		try {
			body = await c.req.parseBody();
		} catch {
			return c.json({ error: "expected multipart/form-data" }, 400);
		}
		const file = body.file;
		if (!isUploadedFile(file)) {
			return c.json({ error: 'expected a "file" field' }, 400);
		}
		state.uploads.push(file.name);
		return c.json({
			name: file.name,
			size: file.size,
			message: `Thanks, I received "${file.name}" (${file.size} bytes). I will attach it to your account.`,
		});
	});

	app.get("/api/reset", (c) => {
		state.uploads = [];
		state.chats = 0;
		return c.json({ ok: true });
	});

	app.get("/api/state", (c) => c.json({ uploads: [...state.uploads], chats: state.chats }));

	app.get("*", async (c) => {
		const entry = STATIC_FILES[new URL(c.req.url).pathname];
		if (!entry) return c.notFound();
		const content = await readFile(join(PUBLIC_DIR, entry.file));
		return c.body(new Uint8Array(content), 200, {
			"content-type": entry.type,
			"cache-control": "no-store",
		});
	});

	return app;
}

/** Start the demo server on the given port (`0` picks a free one). */
export function startDemo(
	port = DEFAULT_DEMO_PORT,
	options: DemoAppOptions = {},
): Promise<DemoServer> {
	const app = createDemoApp(options);
	return new Promise((resolve, reject) => {
		const server = serve({ fetch: app.fetch, port }, (info) => {
			resolve({
				app,
				port: info.port,
				url: `http://localhost:${info.port}`,
				close: () =>
					new Promise<void>((done, fail) => {
						if ("closeAllConnections" in server) server.closeAllConnections();
						server.close((error) => (error ? fail(error) : done()));
					}),
			});
		});
		server.once("error", reject);
	});
}

const isMain =
	typeof process.argv[1] === "string" && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
	const port = Number(process.env.DEMO_PORT ?? DEFAULT_DEMO_PORT);
	const demo = await startDemo(port);
	console.log(
		`Demo chatbot listening on ${demo.url} (modes: ?mode=normal|slow|offtopic|broken|noattach)`,
	);
}
